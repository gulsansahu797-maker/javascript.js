//splice() - adds or removes elements from an array at a specified index and returns the removed elements.
//slice() - returns a shallow copy of a portion of an array into a new array object selected from start to end (end not includes).

//diffrence between splice() and slice() - splice() modifies the original array, while slice() does not modify the original array.

